import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import Fastify from 'fastify';
import pg from 'pg';
import { authorize } from '@homelab/policy';
import { migrate } from '../../core/migrate.js';
import register from './index.js';
import { createActionHandler } from '@homelab/actions/handler';
import { revalidateCapturedAction } from '@homelab/actions';
import { claimJob,runClaimedJob } from '@homelab/worker/runtime';

test('local PostgreSQL action revisions remain immutable and revoked/foreign scopes cannot queue work', {
  skip:!process.env.HOMELAB_LOCAL_PG_URL?'Set throwaway loopback HOMELAB_LOCAL_PG_URL':false,timeout:30000
},async()=>{
  const source=new URL(process.env.HOMELAB_LOCAL_PG_URL!);
  assert.ok(['127.0.0.1','localhost','[::1]'].includes(source.hostname));
  const name=`homelab_actions_${randomUUID().replaceAll('-','')}`;
  const admin=new pg.Pool({connectionString:source.href,max:2});
  let db:pg.Pool|undefined;
  const app=Fastify();
  try {
    await admin.query(`CREATE DATABASE "${name}"`);
    source.pathname=`/${name}`;
    db=new pg.Pool({connectionString:source.href});
    await migrate(db);
    const owner=randomUUID(),foreign=randomUUID(),machine=randomUUID(),otherMachine=randomUUID(),project=randomUUID(),workspace=randomUUID(),grant=randomUUID(),identity=randomUUID();
    await db.query('INSERT INTO users(id,email,password_hash) VALUES($1,$2,$3),($4,$5,$3)',[owner,`${owner}@example.invalid`,'not-a-login',foreign,`${foreign}@example.invalid`]);
    await db.query("INSERT INTO machines(id,owner_id,name,os) VALUES($1,$2,'fixture','linux'),($3,$2,'out of scope','linux')",[machine,owner,otherMachine]);
    await db.query("INSERT INTO projects(id,owner_id,name) VALUES($1,$2,'fixture')",[project,owner]);
    await db.query("INSERT INTO workspaces(id,owner_id,project_id,name,type,machine_id,approved_root_id,canonical_root,runtime_path) VALUES($1,$2,$3,'fixture','native',$4,'fixture','/not-contacted','/not-contacted')",[workspace,owner,project,machine]);
    await db.query('INSERT INTO permission_grants(id,owner_id,tools,machine_ids,workspace_ids) VALUES($1,$2,$3,$4,$5)',[grant,owner,JSON.stringify(['actions.run','run_command']),JSON.stringify([machine]),JSON.stringify([workspace])]);
    await db.query("INSERT INTO execution_identities(id,owner_id,machine_id,name,os_identity,restriction_verified,config) VALUES($1,$2,$3,'disposable fixture','not-executed',true,$4)",[identity,owner,machine,JSON.stringify({workspace_ids:[workspace]})]);
    app.decorateRequest('actor',null);
    app.addHook('preHandler',async request=>{request.actor={id:request.headers['x-fixture-owner']==='foreign'?foreign:owner,role:'owner'};});
    app.setErrorHandler((error,_request,reply)=>{const e=error as Error&{statusCode?:number;code?:string};return reply.code(e.statusCode??400).send({error:{code:e.code??'validation_failed'}});});
    await register(app,{db,policy:authorize,config:{origin:'http://localhost',cookieSecure:false,artifactRoot:'unused',dispatchEnabled:false,restoreMode:false},secrets:{put:async()=>{throw Error('No secrets');},get:async()=>{throw Error('No secrets');}},audit:async(actor,action,target,outcome,details)=>{await db!.query('INSERT INTO audit_events(actor_id,action,target,outcome,details) VALUES($1,$2,$3,$4,$5)',[actor,action,target,outcome,details??{}]);}});
    const command={executable:'/usr/bin/test-runner',args:[{parameter:'suite'}],cwd_policy:'workspace_root'};
    const definition={schema_version:1,machine_ids:[machine],workspace_ids:[workspace],parameters:{suite:{type:'enum',values:['unit','integration']}},command,verification:{command,expected_exit_code:0},limits:{}};
    const created=await app.inject({method:'POST',url:'/actions',payload:{name:'fixture',definition}});
    assert.equal(created.statusCode,201,created.body);
    const action=created.json().id;
    const revised={...definition,description:'second revision'};
    assert.equal((await app.inject({method:'POST',url:`/actions/${action}/revisions`,payload:{expected_revision:1,definition:revised}})).statusCode,201);
    assert.equal((await app.inject({method:'POST',url:`/actions/${action}/revisions`,payload:{expected_revision:1,definition}})).statusCode,409);
    const revisions=(await app.inject({method:'GET',url:`/actions/${action}/revisions`})).json().items;
    assert.deepEqual(revisions.map((r:{revision:number})=>r.revision),[2,1]);
    assert.equal(revisions[1].definition.description,'');
    assert.equal(revisions[0].definition.description,'second revision');
    const payload={revision:1,machine_id:machine,workspace_id:workspace,grant_id:grant,parameters:{suite:'unit'},idempotency_key:'original-revision'};
    const actionOnlyGrant=randomUUID();
    await db.query('INSERT INTO permission_grants(id,owner_id,tools,machine_ids,workspace_ids) VALUES($1,$2,$3,$4,$5)',[actionOnlyGrant,owner,JSON.stringify(['actions.run']),JSON.stringify([machine]),JSON.stringify([workspace])]);
    const missingCommandPermission=await app.inject({method:'POST',url:`/actions/${action}/runs`,payload:{...payload,grant_id:actionOnlyGrant,idempotency_key:'actions-run-is-not-command-authority'}});
    assert.equal(missingCommandPermission.statusCode,403);
    assert.equal(missingCommandPermission.json().error.code,'action_command_permission_denied');
    const queued=await app.inject({method:'POST',url:`/actions/${action}/runs`,payload});
    assert.equal(queued.statusCode,202,queued.body);
    assert.equal(queued.json().payload.action_revision,1);
    assert.equal(queued.json().payload.verification_status,'not_run');
    // Synthetic receipts exercise the real PostgreSQL worker state machine; no host is contacted.
    let launches=0;
    const handler=createActionHandler({executeControl:async()=>{throw Error('Not a helper action');},executeCommand:async(job,_runtime,input)=>{
      let operation=(await db!.query('SELECT * FROM operations WHERE job_id=$1 AND step_id=$2',[job.id,input.step_id])).rows[0];
      if(!operation) {
        launches++;
        operation=(await db!.query("INSERT INTO operations(id,job_id,step_id,request_hash,request,machine_id,fence,status) VALUES($1,$2,$3,'synthetic-receipt',$4,$5,$6,$7) RETURNING *",[randomUUID(),job.id,input.step_id,{fixture:true},machine,job.fence,input.verification?'succeeded':'running'])).rows[0];
        if(!input.verification) return {state:'pending',reason:'synthetic_ack_lost'};
      }
      await db!.query("UPDATE operations SET status='succeeded' WHERE id=$1",[operation.id]);
      return {state:'known',operation_id:operation.id,status:'succeeded',exit_code:0};
    }});
    await db.query('UPDATE runtime_control SET dispatch_enabled=true');
    const first=await claimJob(db,'action-fixture-worker');assert.ok(first);
    await runClaimedJob(db,first,{saved_action:handler});
    assert.equal((await db.query('SELECT state FROM jobs WHERE id=$1',[queued.json().id])).rows[0].state,'waiting');
    assert.equal((await db.query("SELECT count(*)::int AS count FROM resource_reservations WHERE job_id=$1 AND state='held'",[queued.json().id])).rows[0].count,1);
    await db.query('UPDATE jobs SET next_run_at=now() WHERE id=$1',[queued.json().id]);
    const second=await claimJob(db,'replacement-action-worker');assert.ok(second);
    await runClaimedJob(db,second,{saved_action:handler});
    const completed=(await db.query('SELECT state,result FROM jobs WHERE id=$1',[queued.json().id])).rows[0];
    assert.equal(completed.state,'completed');
    assert.equal(completed.result.verification.status,'passed');
    assert.equal(launches,2,'One primary launch and one distinct verification operation');
    assert.equal((await db.query("SELECT count(*)::int AS count FROM resource_reservations WHERE job_id=$1 AND state IN ('held','uncertain')",[queued.json().id])).rows[0].count,0);
    assert.equal((await app.inject({method:'POST',url:`/actions/${action}/runs`,payload:{...payload,idempotency_key:'scope-denied',machine_id:otherMachine}})).statusCode,403);
    assert.equal((await app.inject({method:'POST',url:`/actions/${action}/runs`,headers:{'x-fixture-owner':'foreign'},payload:{...payload,idempotency_key:'foreign-owner'}})).statusCode,404);
    await db.query('UPDATE permission_grants SET revoked_at=now(),revision=revision+1 WHERE id=$1',[grant]);
    assert.equal((await app.inject({method:'POST',url:`/actions/${action}/runs`,payload:{...payload,idempotency_key:'revoked'}})).statusCode,403);
    assert.equal((await db.query('SELECT count(*)::int AS count FROM jobs')).rows[0].count,1);
    assert.equal((await db.query("SELECT count(*)::int AS count FROM audit_events WHERE outcome='denied'")).rows[0].count,4);
    const capabilities=(await app.inject({method:'GET',url:'/actions/capabilities'})).json();
    assert.equal(capabilities.service_controls.configured,false);
    assert.equal(capabilities.container_controls.health_state,'unconfigured');
    await db.query('UPDATE permission_grants SET revoked_at=NULL,revision=revision+1 WHERE id=$1',[grant]);
    const deniedTarget=randomUUID();
    assert.equal((await app.inject({method:'POST',url:'/actions/targets',payload:{id:deniedTarget,machine_id:machine,name:'Missing postcondition permission fixture',kind:'systemd',allowed_operations:['start']}})).statusCode,201);
    const deniedDefinition={schema_version:1,machine_ids:[machine],parameters:{},helper:{type:'systemd',target_id:deniedTarget,operation:'start'},limits:{}};
    const deniedAction=(await app.inject({method:'POST',url:'/actions',payload:{name:'Denied helper fixture',definition:deniedDefinition}})).json().id;
    const deniedRun=await app.inject({method:'POST',url:`/actions/${deniedAction}/runs`,payload:{revision:1,machine_id:machine,grant_id:grant,idempotency_key:'missing-status-permission'}});
    assert.equal(deniedRun.statusCode,403);
    assert.equal(deniedRun.json().error.code,'helper_verification_denied');
    const target=randomUUID();
    assert.equal((await app.inject({method:'POST',url:'/actions/targets',payload:{id:target,machine_id:machine,name:'Disposable helper fixture only',kind:'systemd',allowed_operations:['start','status']}})).statusCode,201);
    const helperDefinition={schema_version:1,machine_ids:[machine],parameters:{},helper:{type:'systemd',target_id:target,operation:'start'},limits:{}};
    const helperAction=(await app.inject({method:'POST',url:'/actions',payload:{name:'Helper fixture',definition:helperDefinition}})).json().id;
    const helperRun={revision:1,machine_id:machine,grant_id:grant,parameters:{},idempotency_key:'helper-verified'};
    const helperQueued=await app.inject({method:'POST',url:`/actions/${helperAction}/runs`,payload:helperRun});
    assert.equal(helperQueued.statusCode,202,helperQueued.body);
    let observedState='running';
    const helperHandler=createActionHandler({executeCommand:async()=>{throw Error('No commands for helper');},executeControl:async(job,_runtime,input)=>{
      const operationId=randomUUID();
      await db!.query("INSERT INTO operations(id,job_id,step_id,request_hash,request,machine_id,fence,status) VALUES($1,$2,$3,'synthetic-control',$4,$5,$6,'succeeded')",[operationId,job.id,input.step_id,{fixture:true},machine,job.fence]);
      return {state:'known',operation_id:operationId,status:'succeeded',result:{status:input.verb==='status'?observedState:'running'}};
    }});
    const helperClaim=await claimJob(db,'helper-fixture');assert.ok(helperClaim);
    await runClaimedJob(db,helperClaim,{saved_action:helperHandler});
    const helperComplete=(await db.query('SELECT state,result FROM jobs WHERE id=$1',[helperQueued.json().id])).rows[0];
    assert.equal(helperComplete.state,'completed');
    assert.equal(helperComplete.result.verification.status,'passed');
    assert.equal((await db.query('SELECT state FROM service_observations WHERE target_id=$1',[target])).rows[0].state,'running');
    assert.equal((await app.inject({method:'GET',url:'/actions/capabilities'})).json().service_controls.health_state,'healthy');
    const failedPostcondition=await app.inject({method:'POST',url:`/actions/${helperAction}/runs`,payload:{...helperRun,idempotency_key:'helper-failed-postcondition'}});
    assert.equal(failedPostcondition.statusCode,202);
    observedState='stopped';
    const failedClaim=await claimJob(db,'failed-postcondition-helper');assert.ok(failedClaim);
    await runClaimedJob(db,failedClaim,{saved_action:helperHandler});
    const failedOutcome=(await db.query('SELECT state,result FROM jobs WHERE id=$1',[failedPostcondition.json().id])).rows[0];
    assert.equal(failedOutcome.state,'failed');
    assert.equal(failedOutcome.result.verification.status,'failed');
    assert.equal(failedOutcome.result.verification.expected,'running');
    assert.equal(failedOutcome.result.verification.observed,'stopped');
    observedState='running';
    const uncertainQueued=await app.inject({method:'POST',url:`/actions/${helperAction}/runs`,payload:{...helperRun,idempotency_key:'helper-unknown'}});
    assert.equal(uncertainQueued.statusCode,202);
    let uncertainCalls=0;
    const uncertainHandler=createActionHandler({executeCommand:async()=>{throw Error('No command');},executeControl:async()=>{uncertainCalls++;return {state:'unknown',reason:'synthetic_lost_host_journal'};}});
    const uncertainClaim=await claimJob(db,'uncertain-helper-fixture');assert.ok(uncertainClaim);
    await runClaimedJob(db,uncertainClaim,{saved_action:uncertainHandler});
    assert.equal((await db.query('SELECT state FROM jobs WHERE id=$1',[uncertainQueued.json().id])).rows[0].state,'interrupted');
    assert.equal((await db.query("SELECT count(*)::int AS count FROM resource_reservations WHERE job_id=$1 AND state='uncertain'",[uncertainQueued.json().id])).rows[0].count,2);
    const blockedQueued=await app.inject({method:'POST',url:`/actions/${helperAction}/runs`,payload:{...helperRun,idempotency_key:'helper-no-replay'}});
    assert.equal(blockedQueued.statusCode,202);
    const blockedClaim=await claimJob(db,'blocked-helper-fixture');assert.ok(blockedClaim);
    await runClaimedJob(db,blockedClaim,{saved_action:uncertainHandler});
    assert.equal((await db.query('SELECT reason FROM jobs WHERE id=$1',[blockedQueued.json().id])).rows[0].reason,'action_target_busy');
    assert.equal(uncertainCalls,1,'Uncertain control is never automatically replayed or bypassed');
    const captured=uncertainQueued.json().payload;
    assert.match(captured.machine_identity_generations[machine],/^[a-f0-9-]{36}$/);
    await db.query('UPDATE machines SET identity_generation=$2 WHERE id=$1',[machine,randomUUID()]);
    await assert.rejects(revalidateCapturedAction(db,owner,captured),{code:'machine_generation_changed'});
  } finally {
    await app.close();
    await db?.end();
    await admin.query(`DROP DATABASE IF EXISTS "${name}" WITH (FORCE)`);
    await admin.end();
  }
});
